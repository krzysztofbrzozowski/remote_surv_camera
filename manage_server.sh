#!/usr/bin/env bash
# Server Management Script (Root Wrapper)
# Usage: ./manage_server.sh [command] [args...]

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SERVER_DIR="$SCRIPT_DIR/server"

# Check if server directory exists
if [ ! -d "$SERVER_DIR" ]; then
    echo "Error: Server directory not found at: $SERVER_DIR"
    exit 1
fi

# Handle init command — interactive .env setup for production
if [ "$1" = "init-prod" ]; then
    ENV_FILE="$SERVER_DIR/.env"

    if [ -f "$ENV_FILE" ]; then
        echo "⚠️  $ENV_FILE already exists."
        read -p "Overwrite? [y/N]: " overwrite
        if [ "$overwrite" != "y" ] && [ "$overwrite" != "Y" ]; then
            echo "Aborted."
            exit 0
        fi
    fi

    umask 077

    echo "🔧 Production .env setup"
    echo "========================"
    echo ""

    # Domain
    read -p "Domain (e.g. camera.example.com): " domain
    if [ -z "$domain" ]; then
        echo "Error: Domain is required."
        exit 1
    fi

    # ACME email (for Let's Encrypt via acme-companion)
    read -p "Email for Let's Encrypt (acme-companion): " acme_email
    if [ -z "$acme_email" ]; then
        echo "Error: ACME email is required."
        exit 1
    fi

    # Django secret key — auto-generate
    echo "🔑 Generating DJANGO_SECRET_KEY..."
    secret_key=$(python3 -c "import secrets, string; print(''.join(secrets.choice(string.ascii_letters + string.digits + '!@#\$%^&*(-_=+)') for _ in range(50)))")

    # Camera token — auto-generate
    echo "🔑 Generating CAMERA_TOKEN..."
    camera_token=$(python3 -c "import secrets; print(secrets.token_urlsafe(32))")

    # STUN server (optional)
    read -p "STUN server (leave empty for LAN/direct IP): " stun_server

    # TURN relay (recommended for production)
    echo ""
    echo "📡 TURN relay (recommended — required for viewers on Symmetric NAT / CGNAT)"
    echo "   Without TURN, some mobile viewers (e.g. Orange PL 5G) will see a black screen."
    echo ""
    read -p "TURN server URL [turn:${domain:-camera.example.com}:3478?transport=udp]: " turn_server

    if [ -n "$turn_server" ] || [ -z "$turn_server" ]; then
        # Default to the server's own IP/domain if user pressed enter
        if [ -z "$turn_server" ]; then
            # Try to resolve the server's public IP for TURN
            public_ip=$(curl -s --max-time 5 https://api.ipify.org 2>/dev/null || echo "")
            if [ -n "$public_ip" ]; then
                turn_server="turn:${public_ip}:3478?transport=udp"
                echo "   Auto-detected public IP: $public_ip"
            else
                turn_server=""
                echo "   ⚠️  Could not detect public IP. Set TURN_SERVER manually in .env"
            fi
        fi
    fi

    turn_username=""
    turn_password=""
    turn_external_ip=""
    turn_port=""
    turn_min_port=""
    turn_max_port=""
    if [ -n "$turn_server" ]; then
        # Extract the IP/host that was auto-detected or entered
        # e.g. turn:203.0.113.10:3478?transport=udp → 203.0.113.10
        auto_ip=$(echo "$turn_server" | sed -E 's|^turn:([^:]+):.*|\1|')
        read -p "TURN external IP (public IP of this server) [${auto_ip}]: " turn_external_ip
        turn_external_ip="${turn_external_ip:-${auto_ip}}"

        read -p "TURN listening port [3478]: " turn_port
        turn_port="${turn_port:-3478}"

        read -p "TURN relay min port [49152]: " turn_min_port
        turn_min_port="${turn_min_port:-49152}"

        read -p "TURN relay max port [49252]: " turn_max_port
        turn_max_port="${turn_max_port:-49252}"

        read -p "TURN username [camrelay]: " turn_username
        turn_username="${turn_username:-camrelay}"

        echo "🔑 Generating TURN_PASSWORD..."
        turn_password=$(python3 -c "import secrets, string; print(''.join(secrets.choice(string.ascii_letters + string.digits) for _ in range(32)))")
        echo "   TURN password generated (saved only in .env)"
    fi

    echo ""
    echo "📝 Writing $ENV_FILE"
    cat > "$ENV_FILE" << EOF
# Production environment — generated by: ./manage_server.sh init-prod
DOMAIN=${domain}
ACME_EMAIL=${acme_email}
# Optional: set DJANGO_ADMIN_PATH to a private URL segment for this installation.
DJANGO_ADMIN_PATH=control-panel
DJANGO_SECRET_KEY=${secret_key}
CAMERA_TOKEN=${camera_token}
STUN_SERVER=${stun_server}

# Network interface for stats monitoring (auto-detected if empty)
# Set to physical NIC name (e.g. eth0, enp1s0) to avoid Docker bridge overcounting
# NETWORK_INTERFACE=
EOF

    # Append TURN config if set
    if [ -n "$turn_server" ]; then
        cat >> "$ENV_FILE" << EOF

# TURN relay — required for viewers behind Symmetric NAT / CGNAT (e.g. mobile carriers)
TURN_SERVER=${turn_server}
TURN_USERNAME=${turn_username}
TURN_PASSWORD=${turn_password}
TURN_EXTERNAL_IP=${turn_external_ip}
TURN_PORT=${turn_port}
TURN_MIN_PORT=${turn_min_port}
TURN_MAX_PORT=${turn_max_port}
EOF
    fi

    chmod 600 "$ENV_FILE"
    echo "✅ .env created at $ENV_FILE"
    echo ""
    if [ -n "$turn_server" ]; then
        echo "⚠️  Firewall: ensure these ports are open:"
        echo "   - ${turn_port}/udp + ${turn_port}/tcp  (TURN signaling)"
        echo "   - ${turn_min_port}:${turn_max_port}/udp  (WebRTC media relay)"
        echo "   Example (UFW):"
        echo "     sudo ufw allow ${turn_port}/udp && sudo ufw allow ${turn_port}/tcp"
        echo "     sudo ufw allow ${turn_min_port}:${turn_max_port}/udp"
        echo ""
    fi
    echo "Next steps:"
    echo "  1. ./manage_server.sh init-cron    (SSH auth monitoring — requires sudo)"
    echo "  2. ./manage_server.sh start prod"
    echo "  3. ./manage_server.sh create-user"
    exit 0
fi

# Handle init-cron command — setup cron job for SSH auth log extraction
if [ "$1" = "init-cron" ]; then
    CRON_SCRIPT="$SERVER_DIR/scripts/extract_ssh_auth.sh"

    if [ ! -f "$CRON_SCRIPT" ]; then
        echo "❌ Script not found: $CRON_SCRIPT"
        exit 1
    fi

    chmod +x "$CRON_SCRIPT"

    echo "🔧 SSH Auth Log Monitoring Setup"
    echo "================================="
    echo ""
    echo "This adds a cron job (runs every minute as root) that extracts SSH"
    echo "auth attempts from /var/log/auth.log to data/ssh_auth.log."
    echo "The Docker container reads this file — no direct auth.log mount needed."
    echo ""
    echo "Cron entry to be added:"
    echo "  * * * * * $CRON_SCRIPT"
    echo ""
    read -p "Install cron job? (requires sudo) [Y/n]: " confirm
    confirm="${confirm:-Y}"

    if [ "$confirm" != "y" ] && [ "$confirm" != "Y" ]; then
        echo "Aborted. You can add it manually:"
        echo "  sudo crontab -e"
        echo "  * * * * * $CRON_SCRIPT"
        exit 0
    fi

    # Add to root crontab (preserving existing entries)
    EXISTING=$(sudo crontab -l 2>/dev/null || true)
    if echo "$EXISTING" | grep -qF "$CRON_SCRIPT"; then
        echo "ℹ️  Cron job already installed"
    else
        (echo "$EXISTING"; echo "* * * * * $CRON_SCRIPT") | sudo crontab -
        echo "✅ Cron job installed"
    fi

    # Run once immediately to populate the data file
    echo "📦 Running initial extraction..."
    sudo "$CRON_SCRIPT"

    LINE_COUNT=$(wc -l < "$SERVER_DIR/data/ssh_auth.log" 2>/dev/null || echo "0")
    echo "✅ Done — $LINE_COUNT SSH auth entries extracted to data/ssh_auth.log"
    exit 0
fi

# Handle local-dev command directly (no Docker)
if [ "$1" = "local-dev" ]; then
    cd "$SERVER_DIR"

    if [ ! -d "venv" ]; then
        echo "❌ venv not found. Run: cd server && ./setup_venv.sh"
        exit 1
    fi

    echo "🚀 Starting local dev server (no Docker)"

    # Start Redis via Docker if not already running
    if docker inspect --format='{{.State.Running}}' surv-redis 2>/dev/null | grep -q true; then
        echo "ℹ️  Redis container already running"
    else
        echo "🔧 Starting Redis via Docker..."
        docker rm -f surv-redis 2>/dev/null || true
        docker run -d --name surv-redis -p 6379:6379 redis:7-alpine >/dev/null
        echo "✅ Redis started on localhost:6379"
    fi

    # Stop Redis on exit
    cleanup() { docker stop surv-redis >/dev/null 2>&1 || true; }
    trap cleanup EXIT

    # Activate venv
    source venv/bin/activate

    # Set dev environment variables
    export DJANGO_SECRET_KEY='dev-key'
    export CAMERA_TOKEN='local-development-placeholder-token'
    export DJANGO_ALLOWED_HOSTS='*'
    export DJANGO_DEBUG=1

    # Run migrations
    echo "📦 Running migrations..."
    python manage.py migrate --run-syncdb

    # Auto-create admin user (admin/admin)
    echo "🔑 Ensuring admin user exists..."
    python manage.py shell -c "
from django.contrib.auth import get_user_model
User = get_user_model()
if not User.objects.filter(username='admin').exists():
    User.objects.create_superuser('admin', 'admin@example.com', 'admin')
    print('✅ Created admin user (username: admin, password: admin)')
else:
    print('ℹ️  Admin user already exists')
"

    # Collect static files
    python manage.py collectstatic --noinput --clear 2>/dev/null || true

    echo ""
    echo "✅ Server ready at http://localhost:8080"
    echo "   Login: admin / admin"
    echo ""

    # Start daphne
    exec daphne -b 0.0.0.0 -p 8080 surv_server.asgi:application
fi

# Handle create-user command — creates a user with 2FA pre-configured
if [ "$1" = "create-user" ]; then
    shift
    # Detect prod vs local
    if docker inspect server-server-1 >/dev/null 2>&1 && docker inspect server-server-1 --format='{{.State.Running}}' | grep -q true; then
        echo "🔧 Creating user on running prod container..."
        docker exec -it server-server-1 python manage.py create_user "$@"
    elif docker inspect surv-server-1 >/dev/null 2>&1 && docker inspect surv-server-1 --format='{{.State.Running}}' | grep -q true; then
        echo "🔧 Creating user on running network container..."
        docker exec -it surv-server-1 python manage.py create_user "$@"
    else
        echo "❌ No running server container found."
        echo "   Start the server first: ./manage_server.sh start [prod]"
        exit 1
    fi
    exit 0
fi

# Handle delete-user command — deletes a user account
if [ "$1" = "delete-user" ]; then
    shift
    if docker inspect server-server-1 >/dev/null 2>&1 && docker inspect server-server-1 --format='{{.State.Running}}' | grep -q true; then
        echo "🔧 Deleting user on running prod container..."
        docker exec -it server-server-1 python manage.py delete_user "$@"
    elif docker inspect surv-server-1 >/dev/null 2>&1 && docker inspect surv-server-1 --format='{{.State.Running}}' | grep -q true; then
        echo "🔧 Deleting user on running network container..."
        docker exec -it surv-server-1 python manage.py delete_user "$@"
    else
        echo "❌ No running server container found."
        echo "   Start the server first: ./manage_server.sh start [prod]"
        exit 1
    fi
    exit 0
fi

# Forward all commands to server/manage.sh
cd "$SERVER_DIR"
exec ./manage.sh "$@"
